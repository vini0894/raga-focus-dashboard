# ─────────────────────────────────────────────────────────
def classify_family(title: str) -> str:
    t = title.lower()
    if re.search(r"(reset|recovery|reboot)", t): return "reset"
    if re.search(r"(healing|comfort|emotional|grief|release)", t): return "healing"
    if re.search(r"(sleep|asleep|insomnia|bedtime|drift off|night)", t): return "sleep"
    if re.search(r"(anxiety|anxious|stress|burnout|panic|overthink|overwhelm)", t): return "anxiety_stress"
    if re.search(r"(calm|peaceful|soothing|relax|gentle|quiet|stillness|tranquil|breathe)", t): return "calm"
    if re.search(r"(focus|concentration|productive|deep work|study|memory|brain fog|clarity|sharp|adhd|cognitive)", t): return "focus"
    if re.search(r"(positive|joyful|happy|uplifting|feel good|bright|cheerful|energy|mood|yoga)", t): return "uplifting"
    if re.search(r"(nostalgia|missing|homesick|memory|memories)", t): return "nostalgia"
    return "other"


def get_instrument(title: str) -> str:
    t = title.lower()
    for inst in ["sitar","veena","sarangi","bansuri","surbahar","sarod","santoor","tanpura",
                 "dilruba","esraj","violin","cello","tabla","bamboo flute","acoustic guitar",
                 "oud","swaramandal"]:
        if inst in t:
            return inst.replace(" ", "_")
    return "none"


def generate_instrument_lane_fit() -> dict:
    """Compute CTR/AVD per (instrument, lane) cell from enriched CSV."""
    enriched_path = DATA_DIR / "shipped_titles_v2_enriched.csv"
    if not enriched_path.exists():
        return {"version": 1, "matrix": {}}

    cells = defaultdict(list)
    instrument_overall = defaultdict(list)
    lane_overall = defaultdict(list)

    with open(enriched_path) as f:
        for r in csv.DictReader(f):
            if r.get("short_form", "").strip().lower() == "true":
                continue
            try:
                ctr = float(r["ctr_pct"]) if r.get("ctr_pct") else None
                avd = float(r["avd_pct"]) if r.get("avd_pct") else None
                views = int(r["views"]) if r.get("views") else 0
            except (ValueError, KeyError):
                continue
            if ctr is None or avd is None:
                continue
            inst = r.get("instrument", "").strip().lower() or "none"
            inst = inst.replace(" ", "_")
            family = r.get("family", "other")
            if family == "other":
                # re-classify if family column is generic
                family = classify_family(r.get("title", ""))
            key = (inst, family)
            cells[key].append({"ctr": ctr, "avd": avd, "views": views, "title": r.get("title","")})
            instrument_overall[inst].append({"ctr": ctr, "avd": avd, "views": views})
            lane_overall[family].append({"ctr": ctr, "avd": avd, "views": views})

    # Build matrix
    matrix = {}
    for (inst, lane), items in cells.items():
        ctrs = [i["ctr"] for i in items]
        avds = [i["avd"] for i in items]
        viewss = [i["views"] for i in items]
        top_title = max(items, key=lambda x: x["avd"])["title"]
        matrix[f"{inst}__{lane}"] = {
            "instrument": inst,
            "lane": lane,
            "n": len(items),
            "ctr_avg": round(mean(ctrs), 2),
            "avd_avg": round(mean(avds), 2),
            "views_med": int(median(viewss)),
            "views_max": max(viewss),
            "top_title": top_title[:80],
        }

    # Instrument overall
    instrument_summary = {}
    for inst, items in instrument_overall.items():
        ctrs = [i["ctr"] for i in items]
        avds = [i["avd"] for i in items]
        instrument_summary[inst] = {
            "n": len(items),
            "ctr_avg": round(mean(ctrs), 2),
            "avd_avg": round(mean(avds), 2),
            "role": classify_instrument_role(inst, mean(ctrs), mean(avds)),
        }

    # Lane overall
    lane_summary = {}
    for lane, items in lane_overall.items():
        ctrs = [i["ctr"] for i in items]
        avds = [i["avd"] for i in items]
        lane_summary[lane] = {
            "n": len(items),
            "ctr_avg": round(mean(ctrs), 2),
            "avd_avg": round(mean(avds), 2),
        }

    return {
        "version": 1,
        "generated_at": datetime.now().isoformat(timespec="seconds"),
        "channel_ctr_avg": 3.63,
        "channel_avd_avg": 21.3,
        "instrument_summary": instrument_summary,
        "lane_summary": lane_summary,
        "matrix": matrix,
    }


def classify_instrument_role(inst: str, ctr_avg: float, avd_avg: float) -> str:
    """Classify instrument role: REACH / RETENTION / CTR_HERO / WORKHORSE / MOONSHOT."""
    # Hand-tuned per playbook §5
    if inst == "sitar":
        return "REACH_HERO"  # algorithm-pushed
    if inst == "veena" and avd_avg >= 26:
        return "RETENTION_HERO"
    if inst == "bansuri" and ctr_avg >= 4.5:
        return "CTR_HERO"
    if inst in {"santoor", "surbahar", "sarangi"}:
        return "WORKHORSE"
    if inst in {"sarod", "esraj", "tanpura"}:
        return "MOONSHOT_UNTESTED_MODERN"
    if inst == "dilruba":
        return "MID_WORKHORSE"
    return "UNCLASSIFIED"


# ─────────────────────────────────────────────────────────
# Main
# ─────────────────────────────────────────────────────────
def main():
    print("Generating phrase_locks.json...")
    locks = generate_phrase_locks(lock_window_days=20)
    locks_path = PLAYBOOK_DIR / "phrase_locks.json"
    locks_path.write_text(json.dumps(locks, indent=2))
    print(f"  ✓ {len(locks['locks'])} locked phrases → {locks_path.relative_to(DASHBOARD_DIR)}")

    print("Generating instrument_lane_fit.json...")
    fit = generate_instrument_lane_fit()
    fit_path = PLAYBOOK_DIR / "instrument_lane_fit.json"
    fit_path.write_text(json.dumps(fit, indent=2))
    print(f"  ✓ {len(fit['matrix'])} instrument×lane cells → {fit_path.relative_to(DASHBOARD_DIR)}")

    # Generated-at marker
    (PLAYBOOK_DIR / "_generated_at.txt").write_text(
        f"playbook_generators.py last run: {datetime.now().isoformat(timespec='seconds')}\n"
    )
    print(f"✓ All auto-generated files updated in {PLAYBOOK_DIR.relative_to(DASHBOARD_DIR)}")


if __name__ == "__main__":
    main()
